"""
app/rate_limiter.py — лимитирование запросов на client_id (этап 5).

Реализация — простая, по заданию этапа 5: словарь в памяти процесса,
внешние хранилища (БД, Redis, файлы) НЕ используются.

Идея: для каждого client_id хранится список временных меток его запросов.
Перед каждой проверкой из списка выбрасываются метки старше окна
(размер окна — RATE_WINDOW_SECONDS из .env), после чего:
  - если оставшихся меток >= RATE_LIMIT_PER_MINUTE — лимит превышен,
    возвращаем False (текущий запрос НЕ регистрируется);
  - иначе добавляем метку текущего запроса и возвращаем True.

Потокобезопасность: все операции со словарём выполняются под
threading.Lock — uvicorn может обрабатывать запросы параллельно, и без
блокировки два запроса одного клиента могли бы одновременно прочитать
список и оба его «разрешить», превысив лимит.
"""

import threading  # блокировка для потокобезопасного доступа к хранилищу
import time  # временные метки запросов (time.monotonic)

from app import config  # RATE_LIMIT_PER_MINUTE, RATE_WINDOW_SECONDS — из .env
from app.logger import setup_logger  # общий логгер приложения

logger = setup_logger("triage.rate_limiter")

# Хранилище лимитов: client_id -> список меток запросов (по возрастанию).
# Живёт в памяти процесса: при перезапуске сервиса история обнуляется —
# это осознанно, простая реализация по заданию.
_request_times: dict[str, list[float]] = {}

# Один Lock на всё хранилище: операции под ним короткие
# (чистка + len + append), поэтому грубая блокировка проще и безопаснее
# зернистой.
_lock = threading.Lock()


def check_rate_limit(client_id: str) -> bool:
    """
    Проверить, разрешён ли запрос клиента (скользящее окно
    RATE_WINDOW_SECONDS секунд).

    Возвращает True, если лимит НЕ превышен (метка запроса добавлена),
    и False, если превышен (метка НЕ добавляется — отказанный запрос
    не должен «съедать» слот у последующих).
    """
    # time.monotonic, а не time.time: монотонные часы не зависят от
    # перевода системного времени, окно не «поедет» при смене даты/часового пояса.
    now = time.monotonic()
    # Граница окна: метки раньше этого момента считаются устаревшими.
    # Размер окна — из .env (RATE_WINDOW_SECONDS).
    cutoff = now - config.RATE_WINDOW_SECONDS

    with _lock:
        # get(...) — не defaultdict: новый client_id появится в словаре
        # только вместе с первым разрешённым запросом (см. ниже).
        times = _request_times.get(client_id)
        if times is None:
            # У клиента ещё не было запросов — лимит точно не превышен,
            # регистрируем первый запрос и выходим.
            _request_times[client_id] = [now]
            return True

        # Выбрасываем устаревшие метки. Список отсортирован по возрастанию,
        # поэтому старые метки идут подряд в начале — находим индекс первой
        # «свежей» метки и удаляем всё до него одним срезом.
        stale = 0
        for stamp in times:
            if stamp > cutoff:
                break
            stale += 1
        if stale:
            del times[:stale]

        if len(times) >= config.RATE_LIMIT_PER_MINUTE:
            # Лимит превышен — логируем (WARNING по заданию) и отказываем.
            # В лог пишем client_id, лимит и сколько запросов в окне:
            # этого достаточно, чтобы разобрать инцидент по logs/app.log.
            logger.warning(
                "RateLimiter: превышен лимит для client_id=%s — "
                "запросов в окне (%s секунд): %s, лимит: %s/мин",
                client_id,
                int(config.RATE_WINDOW_SECONDS),
                len(times),
                config.RATE_LIMIT_PER_MINUTE,
            )
            return False

        # Запрос разрешён — регистрируем его метку в конце списка
        # (список остаётся отсортированным по возрастанию).
        times.append(now)
        return True
